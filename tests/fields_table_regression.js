"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/../desktop/js/scenarioform_fields.js', 'utf8');
const context = vm.createContext({scenarioformEscapeHtml: value => String(value).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;')});
vm.runInContext(source, context);
assert.match(context.scenarioformBuildFieldsTable([]), /Aucun champ/);
const fields = [{id:5, displayOrder:2, label:'A < B', type:'datetime', name:'depart', required:1},{id:6, displayOrder:3, label:'Retour', type:'boolean', name:'retour', required:0}];
const html = context.scenarioformBuildFieldsTable(fields);
assert.match(html, /Date et heure/);
assert.match(html, /Booléen/);
assert.match(html, /A &lt; B/);
assert.match(html, /data-id="5"/);
assert.match(html, /bt_editField/);
assert.match(html, /bt_removeField/);
assert.equal((html.match(/<tr data-id=/g)||[]).length, 2);
assert.equal((html.match(/✓/g)||[]).length, 1);
console.log('Tableau des champs : tests OK');
